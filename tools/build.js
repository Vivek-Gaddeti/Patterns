/* Builds data/index.js from data/patterns/*.js and checks all content with real Python.
   Usage (from the Patters folder):
     node tools/build.js            build index + run every check
     node tools/build.js --fast     build index only
     node tools/build.js hashing    build index + check one pattern            */
const fs = require("fs"), path = require("path"), { spawnSync } = require("child_process");
const ROOT = path.join(__dirname, "..");
global.window = global;
const load = (f) => eval(fs.readFileSync(path.join(ROOT, f), "utf8"));
load("data/catalog.js");
load("assets/judge.js");
global.PATTERNS = {};
global.PAT = (id, d) => { d.id = id; PATTERNS[id] = d; };

const errors = [], warn = (m) => errors.push(m);
const dir = path.join(ROOT, "data/patterns");
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".js"))) {
  try { eval(fs.readFileSync(path.join(dir, f), "utf8")); } catch (e) { warn(`${f}: does not load: ${e.message}`); }
  const id = f.slice(0, -3);
  if (!PATTERNS[id]) warn(`${f}: must call PAT("${id}", …)`);
}
const ids = new Set(CATALOG.map((p) => p.id));
const DIFF = new Set(["Easy", "Medium", "Hard"]);
const PROBLEMS = [], SUMMARY = {}, SPOT = [], seen = new Set();

for (const [pid, d] of Object.entries(PATTERNS)) {
  const where = (x) => `${pid}${x ? " › " + x : ""}`;
  if (!ids.has(pid)) warn(`${pid}: not in catalog`);
  for (const k of ["lede", "time", "space", "idea", "signals", "not", "templates", "examples", "pitfalls", "edge", "compare", "mcq", "summary", "problems"])
    if (d[k] == null) warn(where(`missing "${k}"`));
  (d.compare || []).forEach((c) => { if (!ids.has(c[1])) warn(where(`compare → unknown pattern ${c[1]}`)); });
  (d.mcq || []).forEach((m, i) => { if (!(m[2] >= 0 && m[2] < m[1].length)) warn(where(`mcq ${i} bad answer index`)); });
  const s = d.summary || {};
  for (const k of ["oneLine", "signals", "template", "pitfalls", "cx"]) if (!s[k]) warn(where(`summary missing ${k}`));
  SUMMARY[pid] = { oneLine: s.oneLine, signals: s.signals, template: s.template, pitfalls: s.pitfalls, cx: s.cx };
  if (s.drill) {
    const sig = signature(s.drill.ref || "");
    if (!s.drill.ref) warn(where("drill needs a ref solution"));
    SUMMARY[pid].drill = { task: s.drill.task, fn: sig.fn, starter: starterOf({ solution: s.drill.ref || "" }), tests: s.drill.tests, call: s.drill.call, conv: s.drill.conv };
  }
  (d.problems || []).forEach((P) => {
    const w = (m) => warn(where(`${P.id || "?"}: ${m}`));
    if (!P.id || seen.has(P.id)) w("missing or duplicate id"); seen.add(P.id);
    if (!DIFF.has(P.d)) w("bad difficulty");
    for (const k of ["title", "statement", "examples", "constraints", "hints", "solution", "why", "time", "hidden"]) if (P[k] == null) w(`missing ${k}`);
    if ((P.examples || []).length < 2) w("needs at least 2 examples");
    if ((P.hidden || []).length < 3) w("needs at least 3 hidden tests");
    if ((P.hints || []).length < 2) w("needs at least 2 hints");
    PROBLEMS.push({ id: P.id, title: P.title, d: P.d, pat: pid, lc: P.lc || 0 });
    SPOT.push([String(P.statement).split(/(?<=\.)\s/).slice(0, 2).join(" ").slice(0, 260), pid]);
  });
}
// catalog order, then difficulty
const order = Object.fromEntries(CATALOG.map((p, i) => [p.id, i])), dOrd = { Easy: 0, Medium: 1, Hard: 2 };
PROBLEMS.sort((a, b) => order[a.pat] - order[b.pat] || dOrd[a.d] - dOrd[b.d]);
const PCOUNT = {}; PROBLEMS.forEach((p) => (PCOUNT[p.pat] = (PCOUNT[p.pat] || 0) + 1));

const out = `/* GENERATED by tools/build.js — do not edit by hand. */
window.READY = new Set(${JSON.stringify(Object.keys(PATTERNS))});
window.PROBLEMS = ${JSON.stringify(PROBLEMS.map((p) => [p.id, p.title, p.d, p.pat, p.lc]))}.map(([id, title, d, pat, lc]) => ({ id, title, d, pat, lc }));
window.PCOUNT = ${JSON.stringify(PCOUNT)};
CATALOG.forEach((p) => (p.n = PCOUNT[p.id] || 0));
window.SUMMARY = ${JSON.stringify(SUMMARY)};
window.SPOT = ${JSON.stringify(SPOT)};
`;
fs.writeFileSync(path.join(ROOT, "data/index.js"), out);
console.log(`index: ${Object.keys(PATTERNS).length} patterns, ${PROBLEMS.length} problems (${["Easy", "Medium", "Hard"].map((x) => PROBLEMS.filter((p) => p.d === x).length + " " + x).join(", ")})`);

/* ---------- run everything through Python ---------- */
const only = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!process.argv.includes("--fast")) {
  const jobs = [];
  for (const [pid, d] of Object.entries(PATTERNS)) {
    if (only.length && !only.includes(pid)) continue;
    (d.templates || []).forEach(([t, f, code, outp], i) => jobs.push({ kind: "code", id: `${pid} › template ${t}`, code, expected: outp }));
    (d.examples || []).forEach((x) => jobs.push({ kind: "code", id: `${pid} › example ${x.t}`, code: x.code, expected: x.out }));
    if (d.summary && d.summary.drill && d.summary.drill.ref) {
      const r = d.summary.drill;
      jobs.push({ kind: "problem", id: `${pid} › drill`, solution: r.ref, fn: signature(r.ref).fn, call: r.call, conv: r.conv, cases: r.tests });
    }
    (d.problems || []).forEach((P) => jobs.push({ kind: "problem", id: `${pid} › ${P.id}`, solution: P.solution, fn: signature(P.solution).fn, call: P.call, conv: P.conv,
      cases: [...(P.examples || []).map((e) => [e[0], e[1]]), ...(P.hidden || [])], starter: starterOf(P), brute: P.brute }));
  }
  const tmp = path.join(require("os").tmpdir(), "patterns-check.json");
  fs.writeFileSync(tmp, JSON.stringify({ prelude: PRELUDE, jobs }));
  const r = spawnSync("python", ["-I", path.join(__dirname, "check.py"), tmp], { encoding: "utf8", maxBuffer: 1 << 26 });
  process.stdout.write(r.stdout || ""); process.stderr.write(r.stderr || "");
  if (r.status !== 0) errors.push("python checks failed");
}
if (errors.length) { console.log("\nPROBLEMS:\n  " + errors.join("\n  ")); process.exit(1); }
console.log("all good");
